-- SpringBootBasic : MariaDB 10.6+ 신규 실습 DB용 DDL
-- 주의: 기존 실습 데이터를 자동 변환하는 마이그레이션 스크립트가 아닙니다.
-- 실행 전 데이터베이스와 테이블 이름을 확인하세요.
-- 예) mariadb -u root -p < docs/sql/mariadb_schema.sql

CREATE DATABASE IF NOT EXISTS myDB
    DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE myDB;

CREATE TABLE IF NOT EXISTS USER_INFO (
    USER_ID VARCHAR(50) NOT NULL,
    USER_NAME VARCHAR(100) NOT NULL,
    PASSWORD VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL,
    ADDR1 VARCHAR(255) NULL,
    ADDR2 VARCHAR(255) NULL,
    REG_ID VARCHAR(50) NOT NULL,
    REG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHG_ID VARCHAR(50) NOT NULL,
    CHG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (USER_ID),
    UNIQUE KEY UK_USER_INFO_EMAIL (EMAIL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS NOTICE (
    NOTICE_SEQ BIGINT NOT NULL AUTO_INCREMENT,
    TITLE VARCHAR(200) NOT NULL,
    NOTICE_YN CHAR(1) NOT NULL DEFAULT 'N',
    CONTENTS LONGTEXT NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    READ_CNT INT NOT NULL DEFAULT 0,
    REG_ID VARCHAR(50) NOT NULL,
    REG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHG_ID VARCHAR(50) NOT NULL,
    CHG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (NOTICE_SEQ),
    INDEX IX_NOTICE_REG_DT (REG_DT),
    INDEX IX_NOTICE_USER_ID (USER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS MOVIE_INFO (
    SEQ BIGINT NOT NULL AUTO_INCREMENT,
    COLLECT_TIME CHAR(8) NOT NULL,
    MOVIE_RANK VARCHAR(16) NOT NULL,
    MOVIE_NM VARCHAR(500) NOT NULL,
    MOVIE_RESERVE VARCHAR(50) NULL,
    SCORE VARCHAR(50) NULL,
    OPEN_DAY VARCHAR(30) NULL,
    REG_ID VARCHAR(50) NOT NULL,
    REG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHG_ID VARCHAR(50) NOT NULL,
    CHG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (SEQ),
    INDEX IX_MOVIE_COLLECT_TIME (COLLECT_TIME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS OCR_INFO (
    SEQ BIGINT NOT NULL AUTO_INCREMENT,
    SAVE_FILE_NAME VARCHAR(255) NOT NULL,
    SAVE_FILE_PATH VARCHAR(1024) NOT NULL,
    ORG_FILE_NAME VARCHAR(255) NULL,
    EXT VARCHAR(16) NULL,
    OCR_TEXT LONGTEXT NULL,
    REG_ID VARCHAR(50) NOT NULL,
    REG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHG_ID VARCHAR(50) NOT NULL,
    CHG_DT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (SEQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
